function write(rel, content) {
  const abs = path.join(ROOT, rel);
  outputs.push({ rel, content });
  if (checkMode) return;
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);
}

function cstr(value) {
  if (value == null) return 'nullptr';
  return JSON.stringify(String(value).replace(/[^\x20-\x7e]/g, '?'));
}

function upperSnake(value) {
  return String(value)
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase();
}

function colorEnum(key) {
  if (!theme.colors[key]) throw new Error(`Unknown color "${key}"`);
  return `COL_${upperSnake(key)}`;
}

function fontEnum(key) {
  if (!theme.fonts[key]) throw new Error(`Unknown font "${key}"`);
  return `FONT_${upperSnake(theme.fonts[key])}`;
}

