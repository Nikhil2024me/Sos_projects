function hexTo565(hex) {
  const n = parseInt(hex.replace('#', ''), 16);
  const r = (n >> 16) & 255;
  const g = (n >> 8) & 255;
  const b = n & 255;
  return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
}

function collectBindings() {
  const bindings = new Set();
  const toneBindings = new Set();
  for (const screen of layout.screens) {
    for (const w of screen.widgets) {
      for (const field of ['binding', 'binding2', 'statusBinding', 'valueBinding', 'rightBinding', 'detailBinding']) {
        if (w[field]) bindings.add(w[field]);
      }
      if (w.toneBinding) toneBindings.add(w.toneBinding);
    }
  }
  return { bindings: [...bindings].sort(), toneBindings: [...toneBindings].sort() };
}
